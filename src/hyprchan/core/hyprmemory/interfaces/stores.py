from __future__ import annotations

from typing import Protocol

from hyprchan.core.hyprmemory.models import (
    ConceptNode,
    DreamEntry,
    Episode,
    GraphEdge,
    MemoryQuery,
    PerceptionTrace,
    ProceduralMemory,
    SemanticFact,
    STMItem,
)


class STMStore(Protocol):
    async def append_trace(self, trace: PerceptionTrace) -> None: ...

    async def append_item(self, item: STMItem) -> None: ...

    async def fetch_pending_items(self, limit: int | None = None) -> list[STMItem]: ...

    async def clear_pending_items(self) -> None: ...

    async def count_pending_items(self) -> int: ...


class LTMStore(Protocol):
    async def store_episode(self, episode: Episode) -> None: ...

    async def store_fact(self, fact: SemanticFact) -> None: ...

    async def store_concept(self, concept: ConceptNode) -> None: ...

    async def store_edge(self, edge: GraphEdge) -> None: ...

    async def recent_episodes(self, limit: int) -> list[Episode]: ...

    async def list_concepts(self, limit: int) -> list[ConceptNode]: ...

    async def list_facts(self, limit: int) -> list[SemanticFact]: ...

    async def fetch_edges(self, node_ids: list[str], limit: int) -> list[GraphEdge]: ...

    async def store_dream(self, dream: DreamEntry) -> None: ...

    async def list_dreams(self, limit: int) -> list[DreamEntry]: ...

    async def clear_dreams(self) -> None: ...


class VectorStore(Protocol):
    async def upsert_episode(self, episode: Episode) -> None: ...

    async def upsert_concept(self, concept: ConceptNode) -> None: ...

    async def search_episodes(self, query: MemoryQuery, top_k: int) -> list[Episode]: ...

    async def search_concepts(self, query: MemoryQuery, top_k: int) -> list[ConceptNode]: ...


class ProceduralMemoryStore(Protocol):
    async def upsert(self, memory: ProceduralMemory) -> None: ...

    async def fetch_by_id(self, memory_id: str) -> ProceduralMemory | None: ...

    async def fetch_by_name(self, name: str) -> ProceduralMemory | None: ...

    async def list_recent(self, limit: int) -> list[ProceduralMemory]: ...

    async def search_by_embedding(
        self, query_embedding: list[float], top_k: int
    ) -> list[ProceduralMemory]: ...

    async def query(self, term: str, limit: int) -> list[ProceduralMemory]: ...


class EmbeddingProvider(Protocol):
    async def embed(self, text: str) -> list[float]: ...


class SemanticFeelingJudge(Protocol):
    def project(self, state) -> tuple[str, str, str, float]: ...


class SalienceJudge(Protocol):
    def score(self, *, novelty: float, goal_rel: float, emotion_intensity: float, user_importance: float) -> float: ...
